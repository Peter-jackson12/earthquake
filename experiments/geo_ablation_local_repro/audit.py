"""Independent audit of the T6R local reproduction; never fits a classifier.

Reuses the original T6 inspect()/turnover() and the T5 independent arithmetic()
(not the training score()). Only SHA-verified study joblib files are loaded.
C preprocessing is refit preprocess-only per fold as the projection reference.
Writes full private evidence to --destination and an aggregate-only JSON to --public.
"""
from __future__ import annotations
import argparse
import json
from datetime import datetime, timezone
from pathlib import Path
import joblib
import numpy as np
import pandas as pd
from threadpoolctl import threadpool_limits
from preprocess import GEO
from experiments.age995.run import make_pipeline as original
from experiments.geo_group_cv.audit import arithmetic, check_oof, digest, equal, need, read_json, write_json, PROBS
from experiments.geo_ablation.audit import inspect, turnover
from experiments.geo_ablation_local_repro import run as r

ROOT = Path(__file__).resolve().parents[2]
SUMMARY = ROOT/'reports/geo_ablation_recovery_summary.json'


def audit(data, output, c_stratified_oof, destination, public):
    output, destination = Path(output), Path(destination)
    need(not destination.exists() and not Path(public).exists(), 'Do not overwrite any prior audit')
    run_files_before = {str(p.relative_to(output)): digest(p) for p in sorted(output.rglob('*')) if p.is_file()}
    design = read_json(output/'design.json'); seal = read_json(output/'design_seal.json')
    equal(digest(output/'design.json'), seal['design_sha256'], 'design seal')
    need(design['classifiers_fitted'] == seal['classifiers_fitted'] == 0, 'Not a pre-fit design')
    need(design['c_refits'] == 0 and not design['holdout_accessed'], 'Design boundary')
    for n, h in design['source_sha256'].items():
        equal(digest(ROOT/n), h, 'source '+n)
    X, y, ids, folds, _ = r.verify(data, output)

    ledger = read_json(output/'ledger.json')['folds']
    expected = {r.key(s, v, f) for s in r.SCHEMES for v in r.VARIANTS for f in range(5)}
    equal(sorted(ledger), sorted(expected), 'ledger fold set')
    need(all(e['status'] == 'complete' and e['converged'] for e in ledger.values()), 'Incomplete/nonconverged fold')
    attempts = sum(e['attempts'] for e in ledger.values())
    events = [json.loads(l) for l in (output/'attempts.jsonl').read_text(encoding='utf-8').splitlines()]
    starts = [e for e in events if e.get('action') == 'fit_start']
    equal(len(starts), attempts, 'fit_start events vs ledger attempts')
    need(all(e['started_at_utc'] > seal['created_at_utc'] for e in ledger.values()), 'Fit preceded design seal')
    for e in ledger.values():
        r.check_saved(output, e)

    split_checks = []
    for scheme, cols in [('geo2', GEO[:2]), ('geo1', GEO[:1])]:
        g = pd.factorize(pd.MultiIndex.from_frame(X[cols].astype('int64')))[0]
        need(len(set(g)) == (1408 if scheme == 'geo2' else 31), 'Group population changed')
        for f in range(5):
            a, b = folds[scheme] != f, folds[scheme] == f
            need(not set(g[a]) & set(g[b]), 'Group leakage across train/validation')
            split_checks.append(dict(scheme=scheme, fold=f, valid_rows=int(b.sum()),
                                     valid_groups=len(set(g[b])), group_overlap=0))

    fold_rows, inspections, models, predictions = [], [], [], {}
    pre_fits = 0
    serialization_ulp_max = {}
    for scheme in r.SCHEMES:
        fs = folds[scheme]
        oofs = {}
        for v in r.VARIANTS:
            d = output/scheme/v
            oof = check_oof(pd.read_csv(d/'oof.csv.gz', float_precision='round_trip'), ids, y, fs)
            parts = pd.concat([pd.read_csv(d/f'fold_{f}_pred.csv.gz', float_precision='round_trip')
                               for f in range(5)]).sort_values('building_id', kind='stable').reset_index(drop=True)
            np.testing.assert_array_equal(parts.y_pred, oof.y_pred)
            # run.finalize parsed fold files without round_trip: OOF probabilities may differ by <=1 ulp.
            diff = float(np.abs(parts[PROBS].to_numpy()-oof[PROBS].to_numpy()).max())
            need(diff <= 1e-15, 'Fold prediction files and assembled OOF disagree')
            serialization_ulp_max[scheme, v] = diff
            oofs[v] = oof
        for f in range(5):
            a, b = np.flatnonzero(fs != f), np.flatnonzero(fs == f)
            with threadpool_limits(limits=1):
                cpre = original('C')['preprocess'].fit(X.iloc[a]); pre_fits += 1
                for v in r.VARIANTS:
                    d = output/scheme/v
                    rec = read_json(d/f'fold_{f}.json')
                    equal(digest(d/f'fold_{f}.joblib'), ledger[r.key(scheme, v, f)]['artifact_sha256'][f'fold_{f}.joblib'], 'model SHA')
                    pipe = joblib.load(d/f'fold_{f}.joblib')  # SHA-verified, generated by this study
                    info = inspect(pipe, v, X.iloc[a], X.iloc[b], cpre)
                    equal(rec['median'], info['median'], 'recorded median')
                    equal(rec['encoded_columns'], info['encoded_columns'], 'recorded width')
                    equal(rec['n_iter'], pipe['model'].n_iter_.tolist(), 'recorded iterations')
                    equal(rec['effective_parameters'], original('C')['model'].get_params(), 'LR parameters')
                    np.testing.assert_array_equal(pipe['model'].classes_, [1, 2, 3])
                    oof = oofs[v]
                    np.testing.assert_array_equal(pipe.predict(X.iloc[b]), oof.y_pred.iloc[b])
                    np.testing.assert_allclose(pipe.predict_proba(X.iloc[b]), oof[PROBS].iloc[b], atol=1e-12, rtol=0)
                    calc = arithmetic(y.iloc[b], oof.y_pred.iloc[b])
                    equal(rec['metrics'], calc, 'fold metric (training score vs independent arithmetic)')
                    inspections.append(dict(scheme=scheme, variant=v, fold=f, **info))
                    fold_rows.append(dict(scheme=scheme, variant=v, fold=f, **calc))
                    print('AUDIT', scheme, v, f, 'PASS', flush=True)
        for v in r.VARIANTS:
            d = output/scheme/v
            pred = oofs[v].y_pred.to_numpy(); predictions[scheme, v] = pred
            values = [arithmetic(y[fs == f], pred[fs == f])['macro_f1'] for f in range(5)]
            mean = sum(values)/5; sd = float(np.sqrt(sum((x-mean)**2 for x in values)/4))
            saved = read_json(d/'metrics.json'); pooled = arithmetic(y, pred)
            equal(saved['pooled'], pooled, 'pooled metric')
            np.testing.assert_allclose([saved['cv_mean'], saved['cv_std']], [mean, sd], rtol=0, atol=1e-15)
            equal(saved['oof_sha256'], digest(d/'oof.csv.gz'), 'OOF SHA')
            models.append(dict(scheme=scheme, variant=v, cv_mean=mean, cv_std=sd, fold_macro_f1=values,
                               **pooled, new_fits=5, oof_sha256=saved['oof_sha256']))

    # C baseline: reused verified OOF (stratified, row level); public aggregates only for geo2/geo1.
    equal(digest(c_stratified_oof), design['c_reused_oof_sha256']['stratified'], 'C OOF SHA')
    c_oof = check_oof(pd.read_csv(c_stratified_oof, float_precision='round_trip'), ids, y, folds['stratified'])
    predictions['stratified', 'C'] = c_oof.y_pred.to_numpy()
    summary = read_json(SUMMARY)['baseline_comparisons']
    for scheme in r.SCHEMES:
        if scheme == 'stratified':
            pred = predictions['stratified', 'C']; fs = folds[scheme]
            values = [arithmetic(y[fs == f], pred[fs == f])['macro_f1'] for f in range(5)]
            mean = sum(values)/5; sd = float(np.sqrt(sum((x-mean)**2 for x in values)/4))
            np.testing.assert_allclose([mean, sd], [summary[scheme]['cv_mean'], summary[scheme]['cv_std_ddof1']], atol=1e-12)
            for f in range(5):
                fold_rows.append(dict(scheme=scheme, variant='C', fold=f, **arithmetic(y[fs == f], pred[fs == f])))
            models.append(dict(scheme=scheme, variant='C', cv_mean=mean, cv_std=sd, fold_macro_f1=values,
                               **arithmetic(y, pred), new_fits=0, source='reused verified OOF (row level)'))
        else:
            s = summary[scheme]
            models.append(dict(scheme=scheme, variant='C', cv_mean=s['cv_mean'], cv_std=s['cv_std_ddof1'],
                               fold_macro_f1=s['fold_macro_f1'], **s['pooled'], new_fits=0,
                               source='published T5/recovery aggregate; row-level OOF not available locally'))

    masks = {'all': np.ones(len(X), bool), 'age995': X.age.eq(995).to_numpy(), 'non995': X.age.ne(995).to_numpy()}
    masks.update({'geo1='+g: X.geo_level_1_id.eq(g).to_numpy() for g in sorted(X.geo_level_1_id.unique(), key=int)})
    profiles = [dict(scheme=s, variant=v, group=n, **arithmetic(y[m], p[m]))
                for (s, v), p in predictions.items() for n, m in masks.items() if m.any()]
    paired = []
    groups = {**masks, **{f'fold={f}': folds['stratified'] == f for f in range(5)}}
    for v in r.VARIANTS:
        for n, m in groups.items():
            paired.append(dict(scheme='stratified', variant=v, group=n,
                               **turnover(y[m], predictions['stratified', 'C'][m], predictions['stratified', v][m])))

    run_files_after = {str(p.relative_to(output)): digest(p) for p in sorted(output.rglob('*')) if p.is_file()}
    equal(run_files_after, run_files_before, 'run outputs unchanged by audit')
    contract = read_json(ROOT/'configs/data_contract.json')
    equal({n: digest(Path(data)/n) for n in contract['files']}, contract['files'], 'data preserved')

    destination.mkdir(parents=True)
    for name, rows in [('models', models), ('folds', fold_rows), ('profiles', profiles), ('paired', paired),
                       ('preprocessing', inspections), ('split_checks', split_checks)]:
        write_json(destination/(name+'.json'), rows)
    result = dict(study_id=r.STUDY_ID, status='PASS', audited_at_utc=datetime.now(timezone.utc).isoformat(),
        relation='independent local reproduction; not the original T6 run, which remains unverified',
        code_commit=design['code_commit'], design_sha256=digest(output/'design.json'),
        audit_code_sha256=digest(__file__), environment=design['environment'],
        data_sha256=contract['files'], manifest_sha256=design['manifest_sha256'],
        new_classifier_fits=45, fit_attempts=attempts, c_classifier_refits=0,
        models_reloaded_full_validation=len(inspections), reference_c_preprocessor_only_fits=pre_fits,
        c_projection_checks=len(inspections), excluded_geo_invariance_checks=len(inspections),
        group_leakage_checks=len(split_checks), backup_hash_checks=len(ledger), holdout_accessed=False,
        oof_vs_fold_file_max_abs_prob_diff=max(serialization_ulp_max.values()),
        c_baseline={'stratified': 'reused verified OOF, row level', 'geo2': 'published aggregate only',
                    'geo1': 'published aggregate only'},
        output_sha256={p.name: digest(p) for p in destination.iterdir()},
        limitations=[
            'Separate reproduction run; it does not verify or replace the unrecovered original T6 evidence.',
            'run.finalize re-parsed fold CSVs without round_trip, so assembled OOF probabilities differ from fold '
            'files by <=1 ulp; labels are identical and models reproduce OOF probabilities within 1e-12.',
            'C geo2/geo1 row-level OOF unavailable locally: no paired error turnover for Group CV schemes.',
            'Model reload is not an independent retraining; development-only descriptive CV, no holdout, '
            'no causal leakage proof, no significance test, no external validation.'])
    write_json(destination/'audit.json', result)
    key_groups = {'all', 'age995', 'non995', 'geo1=26', 'geo1=20', 'geo1=13'}
    pub = dict(audit={k: v for k, v in result.items() if k != 'output_sha256'},
               private_audit_sha256=result['output_sha256'], models=models, folds=fold_rows,
               profiles=[p for p in profiles if p['group'].startswith('geo1=') or p['group'] in key_groups],
               paired_stratified=[p for p in paired if p['group'] in key_groups or p['group'].startswith('fold=')])
    write_json(public, pub)
    return result


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--data', default='data'); p.add_argument('--output', required=True)
    p.add_argument('--c-stratified-oof', required=True)
    p.add_argument('--destination', required=True); p.add_argument('--public', required=True)
    a = p.parse_args()
    print(json.dumps(audit(a.data, a.output, a.c_stratified_oof, a.destination, a.public), indent=1)[:2000])


if __name__ == '__main__':
    main()
