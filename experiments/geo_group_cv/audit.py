"""Independent T5 OOF arithmetic, split reconstruction and saved-model audit.

No classifier is fitted. Never reads holdout features/labels. Joblib loading is
limited to explicitly supplied, checksum-verified models generated by this study;
do not use this command on untrusted third-party pickle/joblib packages.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
from datetime import datetime, timezone
import joblib
import numpy as np
import pandas as pd
import sklearn
from scipy import sparse
from sklearn.model_selection import StratifiedGroupKFold
from threadpoolctl import threadpool_limits
from preprocess import load_development, FEATURES, NUMERIC, CATEGORICAL

ROOT = Path(__file__).resolve().parents[2]
PROBS = ['p_grade_1', 'p_grade_2', 'p_grade_3']
FIXED = dict(C=1.0, solver='lbfgs', max_iter=1500, tol=0.0001, random_state=42)


def need(condition, message):
    if not condition:
        raise ValueError(message)


def digest(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        for chunk in iter(lambda: f.read(1024*1024), b''):
            h.update(chunk)
    return h.hexdigest()


def read_json(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def write_json(path, value):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False)+'\n', encoding='utf-8')


def equal(actual, expected, name='value'):
    """Compare saved results, not a saved checksum alone, with recomputation."""
    if isinstance(expected, dict):
        need(isinstance(actual, dict), name+' is not a mapping')
        for key, value in expected.items():
            need(key in actual, name+'.'+key+' missing')
            equal(actual[key], value, name+'.'+key)
    elif expected is None:
        need(actual is None, name+' should be null')
    elif isinstance(expected, (list, tuple)):
        need(len(actual) == len(expected), name+' length mismatch')
        for i, value in enumerate(expected):
            equal(actual[i], value, name+f'[{i}]')
    elif isinstance(expected, (bool, str)):
        need(actual == expected, name+' mismatch')
    elif isinstance(expected, (int, np.integer)):
        need(actual == expected, name+' count mismatch')
    else:
        need(np.isfinite(actual) and abs(float(actual)-float(expected)) <= 1e-11,
             name+' numerical mismatch')


def arithmetic(y, prediction):
    """No sklearn metrics and no training/analysis score helper is reused."""
    y, prediction = np.asarray(y), np.asarray(prediction)
    need(len(y) > 0 and len(y) == len(prediction), 'Empty or unaligned metric inputs')
    need(np.isin(y,[1,2,3]).all() and np.isin(prediction,[1,2,3]).all(), 'Invalid labels')
    cm = np.bincount((3*(y-1)+(prediction-1)).astype(int), minlength=9).reshape(3,3)
    actual, predicted, tp = cm.sum(axis=1), cm.sum(axis=0), cm.diagonal()
    precision = np.divide(tp,predicted,out=np.zeros(3),where=predicted != 0)
    recall = np.divide(tp,actual,out=np.zeros(3),where=actual != 0)
    f1 = np.divide(2*tp,actual+predicted,out=np.zeros(3),where=(actual+predicted) != 0)
    normalized = np.divide(cm,actual[:,None],out=np.zeros((3,3)),where=actual[:,None] != 0)
    return dict(n=int(len(y)),macro_f1=float(f1.sum()/3),accuracy=float(tp.sum()/len(y)),
                precision=precision.tolist(),recall=recall.tolist(),f1=f1.tolist(),support=actual.tolist(),
                confusion=cm.tolist(),normalized_confusion=normalized.tolist(),
                error31=int(cm[2,0]),error32=int(cm[2,1]),
                rate31=float(cm[2,0]/actual[2]) if actual[2] else None,
                rate32=float(cm[2,1]/actual[2]) if actual[2] else None)


def check_oof(frame, ids, y, folds):
    need(set(['building_id','fold','y_true','y_pred']+PROBS) <= set(frame), 'OOF columns missing')
    need(len(frame) == len(ids) and frame.building_id.is_unique, 'Duplicate/missing OOF IDs')
    ordered = frame.sort_values('building_id',kind='stable').reset_index(drop=True)
    np.testing.assert_array_equal(ordered.building_id,ids)
    np.testing.assert_array_equal(ordered.y_true,y)
    np.testing.assert_array_equal(ordered.fold,folds)
    p = ordered[PROBS].to_numpy()
    need(np.isfinite(p).all() and (p >= 0).all() and (p <= 1).all(), 'Invalid probability values')
    np.testing.assert_allclose(p.sum(1),1,atol=1e-7,rtol=0)
    need(np.isin(ordered.y_pred,[1,2,3]).all(), 'Invalid prediction labels')
    np.testing.assert_array_equal(ordered.y_pred,1+p.argmax(1))
    return ordered


def independent_terms(X):
    age = X.age.to_numpy()
    conditions = [age==0,(age>=1)&(age<=10),(age>=11)&(age<=20),(age>=21)&(age<=30),
                  (age>=31)&(age<=50),(age>=51)&(age<=100),(age>=101)&(age<=994),age==995]
    names = ['0','1-10','11-20','21-30','31-50','51-100','101-994','995']
    values = np.select(conditions,names,default='INVALID')
    need(not np.any(values=='INVALID'),'Age outside frozen terms')
    return pd.DataFrame({'age_band':values,'geo_foundation':X.geo_level_1_id.astype(str)+'|'+X.foundation_type.astype(str)},index=X.index)


def inspect_preprocessor(pipe, variant, train, valid):
    base = pipe['preprocess'] if variant=='C' else dict(pipe['preprocess'].transformer_list)['C']
    need(list(train.columns)==FEATURES and 'building_id' not in train,'Input schema changed')
    age_step = base['age995']
    need(age_step.mode=='C','Wrong age policy')
    median = float(np.median(train.age.to_numpy()[train.age.to_numpy()!=995]))
    need(age_step.median_ == median,'Training median mismatch')
    actual_transformed = age_step.transform(base['schema'].transform(train))
    expected_age = np.where(train.age.to_numpy()==995,median,train.age.to_numpy())
    np.testing.assert_array_equal(actual_transformed.age,expected_age)
    np.testing.assert_array_equal(actual_transformed.age_is_995,train.age.to_numpy()==995)
    numeric = train[NUMERIC].to_numpy(dtype=np.float32).copy()
    numeric[:,NUMERIC.index('age')] = expected_age
    numeric = numeric.astype(np.float64)
    means,variances = numeric.mean(0),numeric.var(0)
    scale = np.where(variances==0,1,np.sqrt(variances))
    scaler = base['columns'].named_transformers_['numeric']['scale']
    need(int(scaler.n_samples_seen_) == len(train),'Scaler training denominator mismatch')
    np.testing.assert_allclose(scaler.mean_,means,atol=1e-10,rtol=0)
    np.testing.assert_allclose(scaler.var_,variances,atol=1e-8,rtol=1e-10)
    np.testing.assert_allclose(scaler.scale_,scale,atol=1e-9,rtol=1e-10)
    before = joblib.hash(pipe['preprocess'])
    enc = base['columns'].named_transformers_['categorical']
    need(enc.handle_unknown=='ignore','Unknown category policy changed')
    encoded = enc.transform(valid[CATEGORICAL])
    cats,offset = [],0
    for col,known in zip(CATEGORICAL,enc.categories_):
        need(set(known)==set(train[col]),'Encoder learned nontraining categories: '+col)
        unseen = ~valid[col].isin(set(train[col])).to_numpy()
        need(encoded[unseen,offset:offset+len(known)].nnz==0,'Unknown category block not zero: '+col)
        cats.append(dict(feature=col,train_categories=len(known),valid_categories=int(valid[col].nunique()),
                         unknown_rows=int(unseen.sum()),unknown_unique=int(valid.loc[unseen,col].nunique()),unknown_block_zero=True))
        offset += len(known)
    extras = []
    if variant=='G2':
        extra = dict(pipe['preprocess'].transformer_list)['extra']
        expected_train,expected_valid = independent_terms(train),independent_terms(valid)
        need(list(extra['terms'].columns_)==['age_band','geo_foundation'],'G2 terms changed')
        pd.testing.assert_frame_equal(extra['terms'].transform(train),expected_train)
        pd.testing.assert_frame_equal(extra['terms'].transform(valid),expected_valid)
        need(extra['encode'].handle_unknown=='ignore','Extra unknown policy changed')
        encoded_extra = extra['encode'].transform(expected_valid)
        offset = 0
        for col,known in zip(expected_train,extra['encode'].categories_):
            need(set(known)==set(expected_train[col]),'Extra encoder contamination')
            unknown = ~expected_valid[col].isin(set(expected_train[col])).to_numpy()
            need(encoded_extra[unknown,offset:offset+len(known)].nnz==0,'Unknown extra block not zero')
            extras.append(dict(feature=col,train_categories=len(known),unknown_rows=int(unknown.sum()),
                               unknown_unique=int(expected_valid.loc[unknown,col].nunique()),unknown_block_zero=True))
            offset += len(known)
    transformed = pipe['preprocess'].transform(valid)
    need(sparse.isspmatrix_csr(transformed) and transformed.dtype==np.float32,'Expected sparse float32')
    need(before==joblib.hash(pipe['preprocess']),'Validation mutated preprocessing')
    info = dict(median=median,numeric_mean=scaler.mean_.tolist(),numeric_var=scaler.var_.tolist(),
                numeric_scale=scaler.scale_.tolist(),n_samples_seen=len(train),
                train_age995=int(train.age.eq(995).sum()),valid_age995=int(valid.age.eq(995).sum()),
                categorical=cats,extra=extras,encoded_columns=transformed.shape[1],
                preprocessing_before_after_equal=True,input_columns=list(train.columns),csr_float32=True)
    return info,base


def old_metrics(saved, actual):
    equal(saved['macro_f1'],actual['macro_f1'],'old F1')
    equal(saved['accuracy'],actual['accuracy'],'old accuracy')
    equal(saved['confusion_matrix'],actual['confusion'],'old confusion')
    for i in range(3):
        entry=saved['per_class'][str(i+1)]
        for a,b in [('precision','precision'),('recall','recall'),('f1-score','f1'),('support','support')]:
            equal(entry[a],actual[b][i],'old class '+a)


def audit(data, output, baseline, destination):
    output,baseline,destination=Path(output),Path(baseline),Path(destination)
    need(not (destination/'audit.json').exists(),'Do not overwrite a completed audit')
    destination.mkdir(parents=True,exist_ok=True)
    contract=read_json(ROOT/'configs/data_contract.json')
    before={name:digest(Path(data)/name) for name in contract['files']}
    equal(before,contract['files'],'data SHA')
    X,y,ids,old_cv=load_development(data)
    order=np.argsort(ids.to_numpy(),kind='stable')
    X,y,ids=X.iloc[order].reset_index(drop=True),y.iloc[order].reset_index(drop=True),ids.iloc[order].reset_index(drop=True)
    old_fold=old_cv.test_fold[order]
    need(len(X)==208480 and list(X)==FEATURES,'Development schema changed')
    design,seal=read_json(output/'design.json'),read_json(output/'design_seal.json')
    equal(digest(output/'design.json'),seal['design_sha256'],'design seal')
    equal(design['config'],read_json(Path(__file__).with_name('config.json')),'frozen config')
    equal(design['data_contract'],contract,'design contract')
    need(design['classifiers_fitted']==seal['classifiers_fitted']==0,'Design was not pre-fit')
    need(sklearn.__version__==design['config']['sklearn_version']=='1.8.0','Version mismatch')
    for name,h in design['source_sha256'].items():
        equal(digest(ROOT/name),h,'source '+name)
    models,fold_rows,profiles,unknown_rows,paired,split_rows=[],[],[],[],[],[]
    predictions,split_assignments={},{}
    models_reloaded=0
    for scheme,spec in design['schemes'].items():
        path=output/scheme/'manifest.csv'
        equal(digest(path),spec['manifest_sha256'],'manifest SHA')
        equal(digest(output/scheme/'group_support.csv'),spec['group_support_sha256'],'group support SHA')
        manifest=pd.read_csv(path,dtype={c:str for c in spec['columns']})
        np.testing.assert_array_equal(manifest.building_id,ids)
        need(manifest.building_id.is_unique,'Manifest duplicate IDs')
        for col in spec['columns']:
            np.testing.assert_array_equal(manifest[col],X[col])
        tuples=[tuple(int(v) for v in row) for row in X[spec['columns']].itertuples(index=False,name=None)]
        lookup={key:i for i,key in enumerate(sorted(set(tuples)))}
        codes=np.array([lookup[t] for t in tuples])
        reconstructed=np.full(len(X),-1)
        coverage=np.zeros(len(X),dtype=int)
        for f,(a,b) in enumerate(StratifiedGroupKFold(5,shuffle=True,random_state=42).split(X,y,codes)):
            need(not set(codes[a]) & set(codes[b]),'Geographic leakage')
            need(not set(ids.iloc[a]) & set(ids.iloc[b]),'ID leakage')
            reconstructed[b]=f;coverage[b]+=1
            ta=np.array([(y.iloc[a]==k).sum() for k in [1,2,3]])
            va=np.array([(y.iloc[b]==k).sum() for k in [1,2,3]])
            fractions=va/len(b)
            base=np.array([(y==k).mean() for k in [1,2,3]])
            recomputed=dict(fold=f,train_rows=len(a),valid_rows=len(b),train_groups=len(set(codes[a])),
                            valid_groups=len(set(codes[b])),group_overlap=0,id_overlap=0,train_support=ta.tolist(),
                            valid_support=va.tolist(),valid_class_fraction=fractions.tolist(),
                            max_class_fraction_deviation=float(np.abs(fractions-base).max()))
            equal(spec['folds'][f],recomputed,'fold composition')
            need(min(ta.min(),va.min())>=30 and .01<=len(b)/len(X)<=.5,'Split failed pre-registered gate')
            split_rows.append(dict(scheme=scheme,**recomputed))
        np.testing.assert_array_equal(coverage,np.ones(len(X),dtype=int))
        np.testing.assert_array_equal(reconstructed,manifest.fold)
        need(pd.DataFrame({'group':codes,'fold':manifest.fold}).groupby('group').fold.nunique().max()==1,'Group divided across folds')
        split_assignments[scheme]=reconstructed
        for variant in ['C','G2']:
            directory=output/scheme/variant
            meta=read_json(directory/'metadata.json')
            need(meta['status']=='complete' and meta['attempted_fits']==meta['completed_fits']==5,'Incomplete real training')
            need(meta['started_at_utc']>seal['created_at_utc'],'Training preceded split seal')
            need(not meta['holdout_accessed'],'Holdout boundary violation')
            equal(meta['source_sha256'],design['source_sha256'],'trained source')
            equal(meta['data_contract'],contract,'trained contract')
            equal(meta['design_sha256'],digest(output/'design.json'),'trained design')
            need(meta['environment']['sklearn']=='1.8.0','Training sklearn mismatch')
            for name,h in meta['artifact_sha256'].items():
                equal(digest(directory/name),h,'artifact '+name)
            oof=check_oof(pd.read_csv(directory/'oof.csv.gz',float_precision='round_trip'),ids,y,reconstructed)
            predictions[scheme,variant]=oof.y_pred.to_numpy()
            scores,records=[],read_json(directory/'folds.json')
            need(len(records)==5,'Expected five records')
            for f,record in enumerate(records):
                need(record['fold']==f,'Saved fold order mismatch')
                a,b=np.flatnonzero(reconstructed!=f),np.flatnonzero(reconstructed==f)
                calculated=arithmetic(y.iloc[b],oof.y_pred.iloc[b])
                equal(record['metrics'],calculated,'fold metric')
                scores.append(calculated['macro_f1'])
                equal(digest(directory/f'fold_{f}.joblib'),record['model_sha256'],'model hash')
                pipe=joblib.load(directory/f'fold_{f}.joblib')
                equal(pipe['model'].get_params(),FIXED,'LR settings')
                need(pipe['model'].get_params()['class_weight'] is None,'Unplanned weights')
                np.testing.assert_array_equal(pipe['model'].classes_,[1,2,3])
                with threadpool_limits(limits=1):
                    info,base=inspect_preprocessor(pipe,variant,X.iloc[a],X.iloc[b])
                    equal(record['preprocessing'],info,'preprocessing metadata')
                    np.testing.assert_array_equal(pipe.predict(X.iloc[b]),oof.y_pred.iloc[b])
                    np.testing.assert_allclose(pipe.predict_proba(X.iloc[b]),oof[PROBS].iloc[b],atol=1e-12,rtol=0)
                    if variant=='G2':
                        c_path=output/scheme/'C'/f'fold_{f}.joblib'
                        c_meta=read_json(output/scheme/'C'/'metadata.json')
                        equal(digest(c_path),c_meta['artifact_sha256'][c_path.name],'paired C model SHA')
                        c_pipe=joblib.load(c_path)
                        cmatrix=c_pipe['preprocess'].transform(X.iloc[b])
                        gmatrix=base.transform(X.iloc[b])
                        need(cmatrix.shape==gmatrix.shape and (cmatrix!=gmatrix).nnz==0,'C base block differs between paired models')
                models_reloaded+=1
                equal(record['n_iter'],pipe['model'].n_iter_.tolist(),'iteration count')
                need(record['reload_exact'] is True,'Training reload check absent')
                for kind in ['categorical','extra']:
                    for item in info[kind]:
                        unknown_rows.append(dict(scheme=scheme,variant=variant,fold=f,kind=kind,**item))
                fold_rows.append(dict(scheme=scheme,variant=variant,fold=f,**calculated,
                                      fit_seconds=record['fit_seconds'],n_iter=record['n_iter'][0],
                                      converged=record['converged'],median=info['median']))
                print('AUDIT',scheme,variant,'fold',f,'PASS',flush=True)
            m=read_json(directory/'metrics.json')
            overall=arithmetic(y,oof.y_pred)
            equal(m['pooled'],overall,'pooled metric')
            equal(m['cv_mean'],sum(scores)/5,'CV mean')
            sd=float(np.sqrt(sum((np.array(scores)-np.mean(scores))**2)/4))
            equal(m['cv_std'],sd,'CV sample SD')
            equal(m['effective_parameters'],pipe['model'].get_params(),'effective parameters')
            equal(m['oof_sha256'],digest(directory/'oof.csv.gz'),'OOF declared SHA')
            equal(m['all_converged'],all(r['converged'] for r in records),'convergence summary')
            models.append(dict(scheme=scheme,variant=variant,cv_mean=float(np.mean(scores)),cv_std=sd,
                               **overall,oof_sha256=digest(directory/'oof.csv.gz'),all_converged=m['all_converged'],new_fits=5))
    # Reuse only old C/G2 OOF. No old classifiers are retrained or unpickled.
    baseline_paths={'C':baseline/'age995_abc_v1/C/lr/oof_predictions.csv.gz','G2':baseline/'runs_v1/G2/oof.csv.gz'}
    for variant,path in baseline_paths.items():
        reference=read_json(output/'evidence'/f'baseline_{variant}_verified.json')
        equal(reference['oof_sha256'],digest(path),'baseline OOF SHA')
        oof=check_oof(pd.read_csv(path,float_precision='round_trip'),ids,y,old_fold)
        predictions['stratified',variant]=oof.y_pred.to_numpy()
        scores=[]
        saved=read_json(path.parent/'metrics.json')
        for f in range(5):
            b=old_fold==f
            v=arithmetic(y[b],oof.y_pred[b]);scores.append(v['macro_f1'])
            fold_rows.append(dict(scheme='stratified',variant=variant,fold=f,**v))
        m=arithmetic(y,oof.y_pred)
        old_metrics(saved['oof'] if variant=='C' else saved['pooled'],m)
        equal(saved['cv_macro_f1_mean'] if variant=='C' else saved['cv_mean'],float(np.mean(scores)),'baseline CV mean')
        equal(saved['cv_macro_f1_std'] if variant=='C' else saved['cv_std'],float(np.std(scores,ddof=1)),'baseline CV SD')
        models.append(dict(scheme='stratified',variant=variant,cv_mean=float(np.mean(scores)),cv_std=float(np.std(scores,ddof=1)),
                           **m,oof_sha256=digest(path),all_converged=True,new_fits=0))
    split_assignments['stratified']=old_fold
    for (scheme,variant),pred in predictions.items():
        masks={'all':np.ones(len(X),dtype=bool),'age995':X.age.eq(995).to_numpy(),'non995':X.age.ne(995).to_numpy()}
        masks.update({'geo1='+geo:X.geo_level_1_id.eq(geo).to_numpy() for geo in sorted(X.geo_level_1_id.unique(),key=int)})
        for name,mask in masks.items():
            profiles.append(dict(scheme=scheme,variant=variant,group=name,**arithmetic(y[mask],pred[mask])))
    for scheme,folds in split_assignments.items():
        c,g=predictions[scheme,'C'],predictions[scheme,'G2']
        for group,mask in [('all',np.ones(len(X),dtype=bool)),('age995',X.age.eq(995).to_numpy()),('non995',X.age.ne(995).to_numpy())]+[(f'fold={f}',folds==f) for f in range(5)]:
            truth=y.to_numpy()[mask];cp=c[mask];gp=g[mask]
            a,b=arithmetic(truth,cp),arithmetic(truth,gp)
            ce=(truth==3)&(cp==1);ge=(truth==3)&(gp==1)
            paired.append(dict(scheme=scheme,group=group,n=int(mask.sum()),macro_f1_delta=b['macro_f1']-a['macro_f1'],
                               recall3_delta=b['recall'][2]-a['recall'][2],error31_delta=b['error31']-a['error31'],
                               error32_delta=b['error32']-a['error32'],error31_corrected=int((ce&~ge).sum()),
                               error31_new=int((~ce&ge).sum()),error31_common=int((ce&ge).sum()),
                               prediction_agreement=float(np.mean(cp==gp))))
    need(models_reloaded==20 and sum(m['new_fits'] for m in models)==20,'Expected 20 distinct new models')
    equal({name:digest(Path(data)/name) for name in before},before,'preserved input SHA')
    for name,rows in [('models',models),('folds',fold_rows),('profiles',profiles),('unknown_categories',unknown_rows),('paired',paired),('split_folds',split_rows)]:
        write_json(destination/(name+'.json'),rows)
        pd.DataFrame(rows).to_csv(destination/(name+'.csv'),index=False)
    result=dict(status='PASS',study_id='T5_geo_group_cv_v1',audited_at_utc=datetime.now(timezone.utc).isoformat(),
                development_rows=len(X),new_models=20,new_oof_rows=4*len(X),reused_oof_rows=2*len(X),
                independent_retraining=0,holdout_accessed=False,all_new_models_converged=all(m['all_converged'] for m in models),
                design_sha256=digest(output/'design.json'),audit_code_sha256=digest(__file__),data_sha256=before,
                scopes=dict(split_reconstructed=2,fold_metrics_checked=30,new_models_full_validation_reloaded=20,
                            paired_C_base_block_equal=10,group_profiles=len(profiles),category_records=len(unknown_rows)),
                output_sha256={p.name:digest(p) for p in destination.iterdir() if p.suffix in ['.json','.csv'] and p.name!='audit.json'},
                limitations=['Model reload and learned-statistics checks do not independently re-train or prove every training action.',
                             'Development CV remains exploratory; no new holdout, external earthquake or operational safety validation.',
                             'Fold variability is descriptive, not a confidence interval or a significance test.'])
    write_json(destination/'audit.json',result)
    return result


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--data',default='data')
    p.add_argument('--output',default='outputs/geo_group_cv_v1')
    p.add_argument('--baseline',required=True)
    p.add_argument('--destination',default='outputs/geo_group_cv_v1/audit')
    a=p.parse_args()
    print(json.dumps(audit(a.data,a.output,a.baseline,a.destination),ensure_ascii=False,indent=2))

if __name__=='__main__':
    main()
